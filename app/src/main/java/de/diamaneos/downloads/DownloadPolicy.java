package de.diamaneos.downloads;

import java.net.MalformedURLException;
import java.net.URL;

/** A closed policy vocabulary. No caller or stored value supplies a URL. */
public final class DownloadPolicy {
    public static final int VERSION = 2;
    public static final String AUTOMATIC = "automatic";
    public static final String PRIMARY = "primary_eu";
    public static final String CANADA = "canada";
    public static final DownloadPolicy DEFAULT = new DownloadPolicy(AUTOMATIC);
    private static final String[] MODES = {AUTOMATIC, PRIMARY, CANADA};
    public final String mode;

    private DownloadPolicy(String mode) {
        this.mode = mode;
    }

    public static DownloadPolicy require(Object mode) {
        if (AUTOMATIC.equals(mode)) return DEFAULT;
        if (PRIMARY.equals(mode) || CANADA.equals(mode)) return new DownloadPolicy((String) mode);
        throw new IllegalArgumentException("Unknown download policy");
    }

    public boolean automatic() {
        return AUTOMATIC.equals(mode);
    }

    public String encode() {
        return VERSION + ":" + mode;
    }

    /** Unset and unknown values select Automatic, and so does a version 1 value with fallback on. */
    public static DownloadPolicy decode(String value) {
        if (value == null || value.length() > 32) return DEFAULT;
        for (String mode : MODES) {
            if (value.equals(VERSION + ":" + mode)) return require(mode);
        }
        if (value.equals("1:" + PRIMARY + ":0")) return require(PRIMARY);
        if (value.equals("1:" + CANADA + ":0")) return require(CANADA);
        return DEFAULT;
    }

    /** The servers this policy may use, in their default order. */
    public String[] servers() {
        return automatic() ? new String[]{PRIMARY, CANADA} : new String[]{mode};
    }

    /** The URL on the first server, for callers that need one canonical origin. */
    public URL url(boolean apps, String path) throws MalformedURLException {
        return url(apps, path, servers()[0]);
    }

    public static URL url(boolean apps, String path, String server) throws MalformedURLException {
        if (path == null || !path.matches("[A-Za-z0-9][A-Za-z0-9_./-]{0,511}")) {
            throw new MalformedURLException("Invalid download path");
        }
        for (String part : path.split("/", -1)) {
            if (part.isEmpty() || part.equals(".") || part.equals("..")) {
                throw new MalformedURLException("Invalid download path");
            }
        }
        if (!PRIMARY.equals(server) && !CANADA.equals(server)) {
            throw new MalformedURLException("Unknown download server");
        }
        String host = apps ? "apps" : "releases";
        return new URL("https://" + host + (CANADA.equals(server) ? "-na" : "") + ".diamaneos.de/" + path);
    }

    /** Only canonical Apps URLs generated by this client may enter the HTTP adapter. */
    public static String appsPath(String value) throws MalformedURLException {
        for (String base : new String[]{"https://apps.diamaneos.de/", "https://apps-na.diamaneos.de/"}) {
            if (value != null && value.startsWith(base)) {
                String path = value.substring(base.length());
                url(true, path, PRIMARY);
                return path;
            }
        }
        throw new MalformedURLException("Unapproved Apps origin");
    }
}
